// Normalize answers so capitalization and punctuation do not matter.
function normalizeSequentialAnswer(answer) {
  return String(answer)
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^a-z0-9]/g, "");
}


