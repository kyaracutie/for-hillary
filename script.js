function showSpecialLetter() {
  // Remove an existing letter if there is one.
  const existing = document.getElementById("specialLetterReveal");
  if (existing) existing.remove();

  const overlay = document.createElement("div");
  overlay.id = "specialLetterReveal";
  overlay.className = "special-letter-overlay";

  overlay.innerHTML = `
  <div class="special-letter-paper">
    <button
      type="button"
      class="special-letter-close"
      aria-label="Close letter"
    >×</button>

    <div class="special-letter-content">
      <p class="special-letter-heading"></p>

      <img
        class="special-letter-image"
        alt="A little memory"
      >

      <p class="special-letter-caption"></p>

      <p class="special-letter-greeting"></p>
      <p class="special-letter-message"></p>
      <p class="special-letter-signature"></p>
    </div>
  </div>
  `;

  document.body.appendChild(overlay);
  document.body.style.overflow = "hidden";

  // Insert your editable letter text.
  overlay.querySelector(".special-letter-heading").textContent =
    SPECIAL_LETTER.title;

  overlay.querySelector(".special-letter-image").src =
    SPECIAL_LETTER.image;

  overlay.querySelector(".special-letter-caption").textContent =
    SPECIAL_LETTER.caption;

  overlay.querySelector(".special-letter-greeting").textContent =
    SPECIAL_LETTER.greeting;

  overlay.querySelector(".special-letter-message").textContent =
    SPECIAL_LETTER.message;

  overlay.querySelector(".special-letter-signature").textContent =
    SPECIAL_LETTER.signature;

  // Start the opening animation.
  requestAnimationFrame(() => {
    overlay.classList.add("active");
  });

  const closeLetter = () => {
    overlay.classList.remove("active");

    setTimeout(() => {
      overlay.remove();
      document.body.style.overflow = "";
    }, 400);
  };

  overlay.querySelector(".special-letter-close")
    .addEventListener("click", closeLetter);

  overlay.addEventListener("click", (event) => {
    if (event.target === overlay) {
      closeLetter();
    }
  });
}



